package com.codesquad.mission1.object.fourbasic;

public class Number {
    private final int firstNum;
    private final int secondNum;

    public Number() {
        firstNum = 10;
        secondNum = 2;
    }

    public int getFirstNum() {
        return firstNum;
    }
    public int getSecondNum() {
        return secondNum;
    }
}

